// Screenshots of every main screen at phone / iPad / desktop sizes.
import { launch, VIEWPORTS, URL, seed, track, importVia } from './helpers.mjs';
const engine = process.argv[2] || 'chromium';
const only = process.argv[3];
const b = await launch(engine);
const errs = [];
for (const [name, vp] of Object.entries(VIEWPORTS)) {
  if (only && only !== name) continue;
  const ctx = await b.newContext({ ...vp, permissions: engine === 'chromium' ? ['camera'] : [] });
  if (engine !== 'chromium') await ctx.addInitScript(() => { Object.defineProperty(navigator, 'mediaDevices', { value: { getUserMedia: () => Promise.reject(Object.assign(new Error('no camera'), { name: 'NotFoundError' })) } }); });
  const p = await ctx.newPage();
  track(p, errs);
  const shot = async (n) => { await p.waitForTimeout(600); await p.screenshot({ path: `screenshots/${engine}-${name}-${n}.png` }); };
  await p.goto(URL);
  await p.waitForSelector('[data-testid=hero]');
  await shot('0-home-empty');
  await seed(p, ['test-assets/สัญญา_2567.jpg', 'test-assets/รายงานโครงการ.jpg', 'test-assets/แบบฟอร์มสมัคร.jpg']);
  await p.evaluate(() => { localStorage.setItem('paperx.settings.v1', JSON.stringify({ ...JSON.parse(localStorage.getItem('paperx.settings.v1') || '{}'), onboarded: true })); });
  await p.reload();
  await p.waitForSelector('[data-testid=doc-card]');
  await shot('1-home');
  await p.evaluate(() => (location.hash = '#/library'));
  await p.waitForSelector('[data-testid=lib-grid]');
  await p.locator('[data-testid=doc-select]').first().click();
  await shot('2-library');
  await p.locator('[data-testid=act-open]').click();
  await p.waitForSelector('[data-testid=ed-canvas]');
  await shot('3-editor');
  await p.click('[data-testid=tool-crop]');
  await p.waitForSelector('[data-testid=crop-path]');
  await shot('3b-editor-crop');
  await p.click('[data-testid=crop-cancel]');
  await p.click('[data-testid=tool-filters]');
  await p.waitForSelector('[data-testid=thumb-photo] canvas', { timeout: 20000 });
  await shot('3c-editor-filters');
  await p.keyboard.press('Escape');
  await p.click('[data-testid=tool-compare]');
  await p.waitForSelector('[data-testid=ed-compare]');
  await shot('3d-editor-compare');
  const id = p.url().match(/editor\/([^?]+)/)[1];
  await p.evaluate((id) => (location.hash = '#/export/' + id), id);
  await p.waitForSelector('[data-testid=export-card]');
  await shot('4-export');
  await p.evaluate((id) => (location.hash = '#/ocr/' + id), id);
  await p.waitForSelector('[data-testid=ocr-success]', { timeout: 120000 });
  await shot('5-ocr');
  await p.evaluate(() => (location.hash = '#/settings'));
  await shot('6-settings');
  if (engine === 'chromium') {
    await p.evaluate(() => (location.hash = '#/camera'));
    await p.waitForSelector('[data-testid=cam-quad]', { timeout: 30000 }).catch(() => {});
    await shot('7-camera');
    await p.click('[data-testid=cam-mode-book]');
    await p.waitForSelector('[data-testid=cam-spine]', { timeout: 30000 }).catch(() => {});
    await p.waitForTimeout(2200);
    await shot('7b-camera-book');
    await p.click('[data-testid=cam-mode-doc]');
    await p.click('[data-testid=cam-close]');
  }
  // hero feature: auto flatten (wrinkled page, before/after) and book mode split
  await p.evaluate(() => (location.hash = '#/home'));
  await p.waitForSelector('[data-testid=hero]');
  await p.evaluate(() => document.querySelector('[data-testid=home-book]').scrollIntoView({ block: 'center' }));
  await shot('1b-home-flatten-spotlight');
  await importVia(p, '[data-testid=home-import]', 'test-assets/wrinkled_page.png');
  await p.waitForSelector('[data-testid=ed-canvas]', { timeout: 60000 });
  await p.click('[data-testid=tool-compare]');
  await p.waitForSelector('[data-testid=ed-compare] canvas');
  await p.waitForTimeout(3500);
  await shot('8-flatten-compare');
  await p.click('[data-testid=tool-compare]');
  await p.evaluate(() => (location.hash = '#/home'));
  await p.waitForSelector('[data-testid=hero]');
  await importVia(p, '[data-testid=home-import]', 'test-assets/book_spread.jpg');
  await p.waitForSelector('[data-testid=ed-canvas]', { timeout: 60000 });
  await p.click('[data-testid=tool-book]');
  await p.waitForSelector('[data-testid=book-split]');
  await shot('9a-book-sheet');
  await p.click('[data-testid=book-split]');
  await p.waitForSelector('[data-testid=ed-book-badge]');
  await p.waitForTimeout(3800);
  await shot('9b-book-split');
  await ctx.close();
}
console.log('ERRORS', JSON.stringify(errs, null, 1));
await b.close();
